import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import type { Plugin, ResolvedConfig } from "vite";
import { defineConfig } from "vitest/config";

/**
 * Recursively collects all emitted relative file paths under the build output directory.
 *
 * @param rootDir - Absolute path to the Vite `dist` output directory.
 * @param currentDir - Current directory being traversed during recursion.
 * @returns Sorted list of POSIX-style paths relative to `rootDir` (prefixed with `./`).
 */
function collectOutputAssets(rootDir: string, currentDir: string): string[] {
  const entries = fs.readdirSync(currentDir, { withFileTypes: true });
  const results: string[] = [];

  for (const entry of entries) {
    const fullPath = path.join(currentDir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectOutputAssets(rootDir, fullPath));
      continue;
    }

    const relativePosix = path.relative(rootDir, fullPath).split(path.sep).join("/");
    // 意図: sw.js 自身を事前キャッシュ一覧に含めると、自己更新チェック時に古い Service Worker がキャッシュされやすくなるため除外する。
    if (relativePosix === "sw.js") {
      continue;
    }
    results.push(`./${relativePosix}`);
  }

  return results.sort();
}

/**
 * Computes a deterministic short SHA-256 digest over all emitted build asset contents.
 *
 * @param outDir - Absolute path to the Vite `dist` output directory.
 * @param assetRelativePaths - Relative asset paths prefixed with `./`.
 * @returns 12-character hex digest used as the Service Worker cache generation key.
 */
function computeAssetsHash(outDir: string, assetRelativePaths: string[]): string {
  const hash = createHash("sha256");
  for (const relPath of assetRelativePaths) {
    const normalized = relPath.startsWith("./") ? relPath.slice(2) : relPath;
    const fullPath = path.join(outDir, normalized);
    hash.update(relPath);
    hash.update(fs.readFileSync(fullPath));
  }
  return hash.digest("hex").slice(0, 12);
}

/**
 * Generates the standalone Service Worker JavaScript source for offline caching.
 *
 * @param cacheName - Versioned cache bucket name derived from the emitted build hash.
 * @param precacheUrls - Relative asset URLs (`./`, `./index.html`, `./assets/...`, etc.) to precache.
 * @returns Complete ES5/ES2020-compatible Service Worker script source.
 */
function buildServiceWorkerSource(buildHash: string, precacheUrls: string[]): string {
  return `/* Auto-generated by bg02-studio Vite build plugin. Zero external runtime dependencies. */
const BUILD_HASH = ${JSON.stringify(buildHash)};
const PRECACHE_PATHS = ${JSON.stringify(precacheUrls, null, 2)};

function getCachePrefix() {
  try {
    return "bg02-studio:" + new URL(self.registration.scope).pathname + ":";
  } catch {
    return "bg02-studio:default:";
  }
}

function getCacheName() {
  return getCachePrefix() + BUILD_HASH;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(getCacheName())
      .then((cache) => {
        const scopedRequests = PRECACHE_PATHS.map((relPath) =>
          new URL(relPath, self.registration.scope).toString()
        );
        return cache.addAll(scopedRequests);
      })
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  const prefix = getCachePrefix();
  const activeName = getCacheName();
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(prefix) && key !== activeName)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") {
    return;
  }

  const reqUrl = new URL(req.url);
  // 意図: 同一オリジンかつ自身の Service Worker スコープ配下のみ扱い、完全ローカル完結（外部通信ゼロ）と複数配置時の干渉防止を保つ。
  if (reqUrl.origin !== self.location.origin) {
    return;
  }
  if (!req.url.startsWith(self.registration.scope)) {
    return;
  }

  const activeName = getCacheName();
  event.respondWith(
    caches.open(activeName).then((cache) =>
      cache.match(req).then((cached) => {
        if (cached) {
          return cached;
        }
        return fetch(req)
          .then((response) => {
            if (response && response.ok && response.type === "basic") {
              const copy = response.clone();
              void cache.put(req, copy);
            }
            return response;
          })
          .catch(() => {
            if (req.mode === "navigate") {
              return cache.match(new URL("./index.html", self.registration.scope).toString());
            }
            return Response.error();
          });
      })
    )
  );
});
`;
}

/**
 * Creates a zero-dependency Vite plugin that emits `dist/sw.js` listing all built assets.
 *
 * @returns Configured Vite plugin instance.
 */
function createOfflineSwPlugin(): Plugin {
  let resolvedConfig: ResolvedConfig | null = null;

  return {
    name: "bg02-studio-offline-sw",
    apply: "build",
    configResolved(config) {
      resolvedConfig = config;
    },
    transformIndexHtml() {
      // 意図: 本番ビルド HTML のみに厳格な自己完結 CSP を注入し、外部通信やインラインスクリプト実行をブラウザレベルで抑止する（dev 時の Vite HMR は妨げない）。
      return [
        {
          tag: "meta",
          injectTo: "head",
          attrs: {
            "http-equiv": "Content-Security-Policy",
            content:
              "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' blob: data:; connect-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self';",
          },
        },
      ];
    },
    writeBundle() {
      if (!resolvedConfig) {
        return;
      }
      const outDir = path.resolve(resolvedConfig.root, resolvedConfig.build.outDir);
      if (!fs.existsSync(outDir)) {
        return;
      }

      const discoveredAssets = collectOutputAssets(outDir, outDir);
      // 意図: GitHub Pages 等のサブディレクトリ公開では `./` と `./index.html` の両方でアクセスされるため明示的に両方を含める。
      const precacheUrls = Array.from(new Set(["./", ...discoveredAssets]));
      const buildHash = computeAssetsHash(outDir, discoveredAssets);
      const swSource = buildServiceWorkerSource(buildHash, precacheUrls);

      fs.writeFileSync(path.join(outDir, "sw.js"), swSource, "utf8");
    },
  };
}

/**
 * Vite + Vitest configuration for BG02 Studio.
 *
 * Uses relative base path (`./`) so the static bundle runs identically on GitHub Pages
 * project subpaths (`https://<user>.github.io/<repo>/`) and local HTTPS/localhost servers.
 */
export default defineConfig({
  base: "./",
  plugins: [createOfflineSwPlugin()],
  build: {
    outDir: "dist",
    sourcemap: false,
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.ts"],
  },
});
